"""Anonymized RELEASE COPIES of the tau2_open text artifacts that contain account, path, host or session identifiers.

Writes results/tau2_open/release_anon/ : sanitized copies (same relative path below that directory; large logs and the
raw arm-A results as deterministic .gz) plus MAPPING.json with, for every file, the sha256 of the ORIGINAL, the sha256 of
the sanitized copy and the number of replacements per placeholder. Originals are never edited. No model call, no git
command, no network.

Placeholders:  <REPO> repository root;  <HOME> home directory;  <TMP> per-session / per-user temporary directory
(including the session scratch directory whose name embeds the account and a session id);  <USER> residual account name;
<HOST> machine name;  <SESSION> residual session id.

Only path / name strings are replaced: no number, hash, timestamp or outcome is touched. For JSON files the script
checks that the sanitized copy still parses and that every numeric, boolean and null leaf is identical to the original.

Regeneration is LOCATION-DEPENDENT: the strings to replace are derived at run time from the executing account, the
repository location, the host name and the temp paths found in the files. On another machine or checkout the originals
contain other strings (or git-ignored originals are missing), so no byte-for-byte portability of the anonymized copies
is claimed; original_sha256 ties each copy to its original.

Usage:  .venv/bin/python experiments/tau2_open/make_release_anon.py
"""
from __future__ import annotations
import gzip, hashlib, io, json, platform, re, socket
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[1]
OUT = REPO / 'results' / 'tau2_open' / 'release_anon'

# (relative path, store as gz?)  -- explicit allowlist; nothing else is copied
FILES = [
    ('results/tau2_open/run_manifest.json', False),
    ('experiments/tau2_open/config.json', False),
    ('experiments/tau2_open/README.md', False),
    ('experiments/tau2_open/protocol.md', False),
    ('experiments/tau2_open/config_amendment_1.json', False),
    ('experiments/tau2_open/tests_tau2_open.py', False),
    ('results/tau2_open/report_final_numbers.json', False),
    ('results/tau2_open/run_stdout.log', False),
    ('results/tau2_open/dryrun/run_manifest.json', False),
    ('reviews/tau2_open_preregistration_audit.md', False),
    ('results/tau2_open/logs/tau2_armA.invocation1_preamendment.log', True),
    ('results/tau2_open/logs/tau2_armA.log', True),
    ('results/tau2_open/logs/tau2_armB.log', True),
    ('results/tau2_open/logs/llama_server_8081.log', True),
    ('results/tau2_open/logs/llama_server_8082.log', True),
    ('results/tau2_open/raw/tau2_open_armA.json', True),
]
# originals that are deposited in compressed form: the deposited .gz carries the same identifiers as the file listed above
DEPOSITED_GZ = {
    'results/tau2_open/logs/tau2_armA.invocation1_preamendment.log': 'results/tau2_open/logs_gz/tau2_armA.invocation1_preamendment.log.gz',
    'results/tau2_open/logs/tau2_armA.log': 'results/tau2_open/logs_gz/tau2_armA.log.gz',
    'results/tau2_open/logs/tau2_armB.log': 'results/tau2_open/logs_gz/tau2_armB.log.gz',
    'results/tau2_open/logs/llama_server_8081.log': 'results/tau2_open/logs_gz/llama_server_8081.log.gz',
    'results/tau2_open/logs/llama_server_8082.log': 'results/tau2_open/logs_gz/llama_server_8082.log.gz',
    'results/tau2_open/raw/tau2_open_armA.json': 'results/tau2_open/raw_gz/tau2_open_armA.json.gz',
}
SCAN_DIRS = ['experiments/tau2_open', 'results/tau2_open']
SCAN_EXTRA = ['reviews/tau2_open_final_verification.md', 'reviews/tau2_open_final_verify.py', 'reviews/tau2_open_preregistration_audit.md']
TEXT_SUFFIXES = {'.json', '.md', '.py', '.csv', '.log', '.sha256', '.txt'}
EMAIL = re.compile(r'[A-Za-z0-9._%+-]+@[A-Za-z0-9-]+(?:\.[A-Za-z0-9-]+)*\.[A-Za-z]{2,}')
UUID = r'[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}'
# e-mail addresses at these domains are benchmark data (tau2 airline user records use example.com) or text generated by the evaluated models inside a dialogue
# (support@airline.com, customer.service@delta.com); they identify nobody connected with this work. Every address found is counted per domain in MAPPING.json.
EMAIL_FICTIONAL_DOMAINS = ('example.com', 'airline.com', 'delta.com')
PATTERN_LITERAL_FILES = {'experiments/tau2_open/make_release_anon.py': ('macOS user-directory path', 'temp path')}   # regex literals of this script, not identifiers


def sha(b: bytes) -> str:
    return hashlib.sha256(b).hexdigest()


def identifiers():
    user = Path.home().name
    hosts = sorted({platform.node(), socket.gethostname(), platform.node().split('.')[0]} - {''}, key=len, reverse=True)
    return user, hosts


def rules():
    """Ordered (placeholder, compiled regex) list. Longest / most specific first."""
    user, hosts = identifiers()
    home = str(Path.home()); repo = str(REPO)
    mangled = re.escape(repo.replace('/', '-'))            # the session temp directory embeds the repository path with '/' -> '-'
    rs = [
        ('<TMP>', re.compile(r'(?:/private)?/tmp/claude-\d+/' + mangled + r'/' + UUID + r'/scratchpad')),
        ('<TMP>', re.compile(r'(?:/private)?/tmp/claude-\d+/' + mangled + r'/' + UUID)),
        ('<TMP>', re.compile(r'(?:/private)?/tmp/claude-\d+/[^/\s"\'\\]+/' + UUID + r'(?:/scratchpad)?')),
        ('<TMP>', re.compile(r'(?:/private)?/var/folders/[A-Za-z0-9_]+/[A-Za-z0-9_]+/T')),
        ('<REPO>', re.compile(re.escape(repo))),
        ('<HOME>', re.compile(re.escape(home))),
        ('<TMP>', re.compile(mangled)),
    ]
    rs += [('<HOST>', re.compile(re.escape(h), re.I)) for h in hosts]
    rs += [('<USER>', re.compile(re.escape(user), re.I))]
    return rs, user, hosts


def session_ids(texts) -> list:
    ids = set()
    for t in texts:
        ids.update(re.findall(r'/tmp/claude-\d+/[^/\s"\'\\]+/(' + UUID + ')', t))
    return sorted(ids)


def sanitize(text: str, rs, sess) -> tuple:
    counts = {}
    for ph, rx in rs:
        text, n = rx.subn(ph, text)
        if n:
            counts[ph] = counts.get(ph, 0) + n
    for sid in sess:                                         # residual bare session id (not part of a path)
        n = text.count(sid)
        if n:
            text = text.replace(sid, '<SESSION>'); counts['<SESSION>'] = counts.get('<SESSION>', 0) + n
    return text, counts


def indicators(text: str, user: str, hosts, sess) -> list:
    low = text.lower(); out = []
    if '/Users/' in text:
        out.append('macOS user-directory path')
    if re.search(r'/home/[A-Za-z0-9_.-]+', text):
        out.append('linux home-directory path')
    if user.lower() in low:
        out.append('account name')
    elif len(user) >= 8 and user[:6].lower() in low:
        out.append('6-character prefix of the account name')
    if any(h.lower() in low for h in hosts):
        out.append('host name')
    if re.search(r'/tmp/claude-\d+|/var/folders/', text):
        out.append('temp path')
    if any(s in text for s in sess):
        out.append('session id')
    em = sorted({m for m in EMAIL.findall(text) if m.split('@')[1].lower() not in EMAIL_FICTIONAL_DOMAINS})
    if em:
        out.append('e-mail address outside the fictional-domain list x%d' % len(em))
    return out


def email_domains(text: str) -> dict:
    d = {}
    for m in EMAIL.findall(text):
        k = m.split('@')[1].lower(); d[k] = d.get(k, 0) + 1
    return d


def leaves(o, path=''):
    if isinstance(o, dict):
        for k, v in o.items():
            yield from leaves(v, path + '/' + str(k))
    elif isinstance(o, list):
        for i, v in enumerate(o):
            yield from leaves(v, '%s[%d]' % (path, i))
    elif o is None or isinstance(o, (bool, int, float)):
        yield path, repr(o)


def gz_bytes(b: bytes) -> bytes:
    buf = io.BytesIO()
    with gzip.GzipFile(filename='', mode='wb', fileobj=buf, mtime=0, compresslevel=9) as g:   # deterministic: no name, no mtime
        g.write(b)
    return buf.getvalue()


def main():
    rs, user, hosts = rules()
    originals = {}
    for rel, _ in FILES:
        p = REPO / rel
        if p.exists():
            originals[rel] = p.read_bytes()
    sess = session_ids(b.decode('utf-8', errors='replace') for b in originals.values())
    OUT.mkdir(parents=True, exist_ok=True)
    mapping = []
    for rel, as_gz in FILES:
        if rel not in originals:
            mapping.append(dict(file=rel, status='original unavailable in this checkout (git-ignored or not present); no copy made')); continue
        raw = originals[rel]; text = raw.decode('utf-8')
        new, counts = sanitize(text, rs, sess)
        dst = OUT / (rel + ('.gz' if as_gz else ''))
        dst.parent.mkdir(parents=True, exist_ok=True)
        payload = new.encode('utf-8')
        dst.write_bytes(gz_bytes(payload) if as_gz else payload)
        rec = dict(file=rel, anonymized_copy=str(dst.relative_to(REPO)), original_sha256=sha(raw), original_bytes=len(raw),
                   anonymized_sha256=sha(payload), anonymized_bytes=len(payload), replacements=counts, changed=new != text,
                   lines_original=text.count('\n'), lines_anonymized=new.count('\n'))
        if as_gz:
            rec.update(stored_as='gzip (mtime 0, no embedded name); anonymized_sha256 is of the UNCOMPRESSED sanitized text', stored_gz_sha256=sha(dst.read_bytes()),
                       stored_gz_bytes=dst.stat().st_size)
        if rel in DEPOSITED_GZ:
            g = REPO / DEPOSITED_GZ[rel]
            if g.exists():
                same = gzip.decompress(g.read_bytes()) == raw
                rec.update(deposited_compressed_original=DEPOSITED_GZ[rel], deposited_compressed_original_sha256=sha(g.read_bytes()),
                           deposited_compressed_original_decompresses_to_this_original=bool(same))
        if rel.endswith('.json'):
            a = dict(leaves(json.loads(text))); b = dict(leaves(json.loads(new)))
            rec.update(json_parses=True, numeric_boolean_null_leaves=len(a), numeric_boolean_null_leaves_identical=a == b)
            assert a == b, rel
        assert rec['lines_original'] == rec['lines_anonymized'], rel
        mapping.append(rec)

    # ---- scan 1: the anonymized tree itself (decompressing .gz)
    tree_hits = []; n_tree = 0; domains = {}
    for p in sorted(OUT.rglob('*')):
        if not p.is_file() or p.name == 'MAPPING.json':
            continue
        n_tree += 1
        t = (gzip.decompress(p.read_bytes()) if p.suffix == '.gz' else p.read_bytes()).decode('utf-8', errors='replace')
        for ind in indicators(t, user, hosts, sess):
            tree_hits.append(dict(file=str(p.relative_to(REPO)), indicator=ind))
        for k, v in email_domains(t).items():
            domains[k] = domains.get(k, 0) + v

    # ---- scan 2: every other tau2_open text artifact (not copied): which originals are clean, which are not covered
    listed = {rel for rel, _ in FILES}
    clean, dirty = [], []
    cands = [p for d in SCAN_DIRS for p in sorted((REPO / d).rglob('*'))] + [REPO / x for x in SCAN_EXTRA]
    for p in cands:
        if not p.is_file() or OUT in p.parents or '__pycache__' in p.parts:
            continue
        rel = str(p.relative_to(REPO))
        if rel in listed:
            continue
        if p.suffix == '.gz':
            try:
                t = gzip.decompress(p.read_bytes()).decode('utf-8', errors='replace')
            except OSError:
                continue
        elif p.suffix in TEXT_SUFFIXES:
            t = p.read_text(errors='replace')
        else:
            continue
        ind = [i for i in indicators(t, user, hosts, sess) if i not in PATTERN_LITERAL_FILES.get(rel, ())]
        (dirty if ind else clean).append(dict(file=rel, indicators=ind) if ind else rel)
    covered = {v: k for k, v in DEPOSITED_GZ.items()}
    raw_dir = 'results/tau2_open/raw/'
    for d in dirty:
        if d['file'] in covered:
            d['covered_by'] = 'results/tau2_open/release_anon/' + covered[d['file']] + '.gz'
        elif d['file'].startswith(raw_dir) and d['file'] != raw_dir + 'tau2_open_armA.json':
            d['covered_by'] = 'results/tau2_open/release_anon/results/tau2_open/raw/tau2_open_armA.json.gz (byte-identical per-invocation copy of the canonical arm-A file)' \
                if sha((REPO / d['file']).read_bytes()) == sha(originals.get(raw_dir + 'tau2_open_armA.json', b'')) else None
        else:
            d['covered_by'] = None

    out = dict(
        placeholders={'<REPO>': 'repository root', '<HOME>': "user's home directory", '<TMP>': 'per-user or per-session temporary directory (the session scratch directory)',
                      '<USER>': 'account name (residual or case-variant occurrences)', '<HOST>': 'machine network name', '<SESSION>': 'session id outside a path'},
        note='Originals are unmodified; original_sha256 lets a holder of the originals verify the correspondence. Only path/name strings were replaced; no number, hash, '
             'timestamp or outcome was touched; line counts are unchanged; JSON copies parse and have identical numeric/boolean/null leaves.',
        portability='Regeneration of the anonymized copies is LOCATION-DEPENDENT: the strings that are replaced are derived at run time from the executing account, '
                    'repository location, host name and the temp/session paths found in the files, and a different checkout may lack git-ignored originals (logs/, raw/). '
                    'No byte-for-byte portability of the anonymized copies is claimed; original_sha256 ties each committed copy to its original.',
        scope='tau2_open only. An anonymous release must be packaged from this explicit allowlist: the sanitized copies listed under files, plus the originals listed under '
              'clean_originals. Files listed under originals_with_identifiers must NOT be released as they are (this includes the deposited logs_gz/*.gz and '
              'raw_gz/tau2_open_armA.json.gz, which carry the same strings as their uncompressed originals).',
        generated_by='experiments/tau2_open/make_release_anon.py', files=mapping,
        scan_of_anonymized_tree=dict(n_files=n_tree, indicators_searched=['macOS user-directory path', 'linux home-directory path', 'account name (case-insensitive)', '6-character prefix of the account name',
                                                                          'host names', 'per-session and per-user temp paths', 'session ids', 'e-mail patterns'],
                                     hits=tree_hits, clean=len(tree_hits) == 0, email_addresses_by_domain=domains,
                                     email_note='all e-mail addresses in the tree are tau2 benchmark records (example.com) or model-generated dialogue text '
                                                '(airline.com, delta.com); an address at any other domain is reported as a hit'),
        clean_originals=clean, originals_with_identifiers=dirty,
        originals_with_identifiers_not_covered_by_a_copy=[d['file'] for d in dirty if not d.get('covered_by')])
    (OUT / 'MAPPING.json').write_text(json.dumps(out, indent=2))
    mt = (OUT / 'MAPPING.json').read_text()
    assert not indicators(mt, user, hosts, sess), 'MAPPING.json itself contains an identifier'
    print(json.dumps(dict(files=len(mapping), changed=sum(bool(m.get('changed')) for m in mapping), tree_files=n_tree, tree_hits=tree_hits,
                          not_covered=out['originals_with_identifiers_not_covered_by_a_copy'], n_clean_originals=len(clean)), indent=2))


if __name__ == '__main__':
    main()
